export interface ParsedUserContext {
  name: string;
  workStatus: string;
  isStudent: boolean;
  isEmployee: boolean;
  isBusiness: boolean;
  isJobSeeker: boolean;
  isRetired: boolean;
  incomeStability: string;
  isVariableIncome: boolean;
  isFixedIncome: boolean;
  incomeSource: string;
  ageGroup: string;
  isYoungAdult: boolean;
  isOlderAdult: boolean;
  hasDependents: boolean;
  hasDependentsExplicitNo: boolean;
  dependentsLabel: string;
  currentFocus: string;
}

export interface DomainContextConfig {
  contextIntro: string;
  openingQuestion: string;
  description: string;
  placeholder: string;
  followUpProbe: string;
  suggestedResponses: string[];
  guidanceNote: string;
  exploratoryQuestions: string[];
}

export function parseUserContext(
  userProfile?: Record<string, any> | null,
  fallbackName?: string
): ParsedUserContext {
  const name =
    (typeof userProfile?.name === 'string' && userProfile.name.trim()) ||
    (typeof fallbackName === 'string' && fallbackName.trim()) ||
    'عزيزي';

  const workStatus = String(
    userProfile?.employmentStatus || userProfile?.workStatus || ''
  ).trim();

  const isStudent = workStatus === 'طالب جامعي' || workStatus.includes('طالب');
  const isBusiness =
    workStatus === 'صاحب عمل/مستقل' ||
    workStatus === 'صاحب عمل' ||
    workStatus === 'مستقل' ||
    workStatus.includes('صاحب عمل') ||
    workStatus.includes('مستقل');
  const isJobSeeker = workStatus === 'باحث عن عمل' || workStatus.includes('باحث');
  const isRetired = workStatus === 'متقاعد' || workStatus.includes('متقاعد');
  const isEmployee =
    !isStudent &&
    !isBusiness &&
    !isJobSeeker &&
    !isRetired &&
    (workStatus === 'موظف' || workStatus.includes('موظف') || workStatus.includes('قطاع') || workStatus.includes('حكومي'));

  const incomeStability = String(userProfile?.incomeStability || '').trim();
  const incomeSource = String(userProfile?.incomeSource || '').trim();
  const isVariableIncome =
    incomeStability.includes('متغير') ||
    incomeStability.includes('تذبذب') ||
    (isBusiness && !incomeStability.includes('ثابت'));
  const isFixedIncome =
    !isVariableIncome &&
    (incomeStability.includes('ثابت') ||
      incomeStability.includes('منتظم') ||
      isEmployee ||
      isRetired);

  const ageGroup = String(userProfile?.ageGroup || '').trim();
  const isYoungAdult =
    ageGroup.includes('أقل من 20') ||
    ageGroup.includes('20 - 29') ||
    ageGroup === '20-29';
  const isOlderAdult =
    ageGroup.includes('50') ||
    ageGroup.includes('60') ||
    isRetired;

  const rawDep = userProfile?.hasDependents;
  const depStr = typeof rawDep === 'string' ? rawDep.trim() : '';
  const hasDependents =
    rawDep === true ||
    depStr === 'نعم' ||
    depStr.startsWith('نعم') ||
    depStr.includes('أسرة') ||
    depStr.includes('أطفال') ||
    depStr.includes('عائلة') ||
    depStr === 'yes';
  const hasDependentsExplicitNo =
    rawDep === false ||
    depStr === 'لا' ||
    depStr.includes('بدون') ||
    depStr === 'no';

  const dependentsLabel = hasDependents
    ? depStr && depStr !== 'نعم'
      ? depStr
      : 'نعم (لديه أسرة أو معالون)'
    : hasDependentsExplicitNo
      ? 'لا (بدون معالين)'
      : 'غير محدد';

  const currentFocus = String(userProfile?.currentFocus || '').trim();

  return {
    name,
    workStatus: workStatus || 'غير محدد',
    isStudent,
    isEmployee,
    isBusiness,
    isJobSeeker,
    isRetired,
    incomeStability,
    isVariableIncome,
    isFixedIncome,
    incomeSource,
    ageGroup,
    isYoungAdult,
    isOlderAdult,
    hasDependents,
    hasDependentsExplicitNo,
    dependentsLabel,
    currentFocus,
  };
}

function getStudentIncomeLabel(ctx: ParsedUserContext): string {
  if (ctx.incomeSource.includes('مكافأة')) return 'مكافأتك الجامعية';
  if (ctx.incomeSource.includes('مصروف')) return 'مصروفك الشهري';
  if (ctx.incomeSource.includes('جزئي')) return 'دخلك من العمل الجزئي';
  return ctx.incomeSource || 'مكافأتك أو مصروفك الجامعي';
}

