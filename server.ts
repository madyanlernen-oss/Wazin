        reasoning: `تحليل ترحيبي وتأسيس المساحة الآمنة: المستفيد (${userName}) يبادر بالتحية، والمطلوب هو كسر حاجز الرسمية وفتح أفق الحوار حول الصفاء والسكينة الداخلية وعلاقتها بتدفق اليوم.`,
